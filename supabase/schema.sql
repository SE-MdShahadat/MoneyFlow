-- =====================================================================
-- MoneyFlow database (Supabase / PostgreSQL)
-- Run once in Supabase Dashboard → SQL Editor on an empty project.
-- Security model:
--   * Anyone can sign up, but gets NO access until an admin approves them
--     (profiles.is_active). The very first account becomes the active Admin.
--   * Admin: manages accounts, categories, members; can edit any entry.
--   * Member: reads everything, adds entries, edits/deletes only their own.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------
create table public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  name        text not null check (char_length(name) between 1 and 100),
  email       text,
  relation    text check (relation is null or char_length(relation) <= 50),
  role        text not null default 'Member' check (role in ('Admin', 'Member')),
  is_active   boolean not null default false,
  created_at  timestamptz not null default now()
);

create table public.accounts (
  id               bigint generated always as identity primary key,
  name             text not null check (char_length(name) between 1 and 100),
  type             text not null check (type in ('Cash', 'Bank', 'MobileBanking', 'Card', 'Other')),
  opening_balance  numeric(18, 2) not null default 0,
  note             text check (note is null or char_length(note) <= 500),
  is_active        boolean not null default true,
  created_at       timestamptz not null default now()
);

create table public.categories (
  id          bigint generated by default as identity primary key,
  name_en     text not null check (char_length(name_en) between 1 and 100),
  name_bn     text not null check (char_length(name_bn) between 1 and 100),
  type        text not null check (type in ('Income', 'Expense')),
  icon        text not null default '📦' check (char_length(icon) <= 20),
  color       text not null default '#64748b' check (char_length(color) <= 20),
  sort_order  int not null default 0,
  is_active   boolean not null default true
);

create table public.transactions (
  id             bigint generated always as identity primary key,
  type           text not null check (type in ('Income', 'Expense', 'Transfer')),
  amount         numeric(18, 2) not null check (amount > 0),
  date           date not null,
  account_id     bigint not null references public.accounts (id) on delete restrict,
  to_account_id  bigint references public.accounts (id) on delete restrict,
  category_id    bigint references public.categories (id) on delete restrict,
  member_id      uuid references public.profiles (id) on delete restrict,
  note           text check (note is null or char_length(note) <= 500),
  created_by     uuid not null default auth.uid() references public.profiles (id) on delete restrict,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz,
  constraint transactions_shape check (
       (type = 'Transfer' and to_account_id is not null and to_account_id <> account_id and category_id is null)
    or (type <> 'Transfer' and category_id is not null and to_account_id is null))
);

create index transactions_date_idx on public.transactions (date desc, id desc);
create index transactions_account_idx on public.transactions (account_id);
create index transactions_to_account_idx on public.transactions (to_account_id);
create index transactions_category_idx on public.transactions (category_id);
create index transactions_member_idx on public.transactions (member_id);
create index transactions_created_by_idx on public.transactions (created_by);

-- ---------------------------------------------------------------------
-- Helper checks used by the security policies
-- ---------------------------------------------------------------------
create function public.is_member() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and is_active);
$$;

create function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and is_active and role = 'Admin');
$$;

-- ---------------------------------------------------------------------
-- Triggers
-- ---------------------------------------------------------------------

-- A profile is created for every new sign-up. The first one becomes the active Admin.
create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  first_user boolean;
begin
  perform pg_advisory_xact_lock(727274);
  select not exists (select 1 from public.profiles) into first_user;
  insert into public.profiles (id, name, email, role, is_active)
  values (
    new.id,
    left(coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), split_part(new.email, '@', 1)), 100),
    new.email,
    case when first_user then 'Admin' else 'Member' end,
    first_user);
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Keeps identity columns fixed and never lets the family lose its last active admin.
create function public.guard_profile_update() returns trigger
language plpgsql set search_path = public as $$
begin
  new.id := old.id;
  new.email := old.email;
  new.created_at := old.created_at;
  if old.role = 'Admin' and old.is_active and (new.role <> 'Admin' or not new.is_active)
     and not exists (select 1 from public.profiles
                     where id <> old.id and role = 'Admin' and is_active) then
    raise exception 'LAST_ADMIN';
  end if;
  return new;
end;
$$;

create trigger profiles_guard
  before update on public.profiles
  for each row execute function public.guard_profile_update();

-- Category must match the entry type; author and timestamps are set by the server.
create function public.prepare_transaction() returns trigger
language plpgsql set search_path = public as $$
begin
  if new.type <> 'Transfer' and not exists (
       select 1 from public.categories c where c.id = new.category_id and c.type = new.type) then
    raise exception 'CATEGORY_REQUIRED';
  end if;
  if tg_op = 'INSERT' then
    new.created_by := auth.uid();
    new.created_at := now();
    new.updated_at := null;
  else
    new.created_by := old.created_by;
    new.created_at := old.created_at;
    new.updated_at := now();
  end if;
  return new;
end;
$$;

create trigger transactions_prepare
  before insert or update on public.transactions
  for each row execute function public.prepare_transaction();

-- ---------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.accounts enable row level security;
alter table public.categories enable row level security;
alter table public.transactions enable row level security;

create policy profiles_read on public.profiles
  for select to authenticated using (id = auth.uid() or public.is_member());
create policy profiles_admin_update on public.profiles
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

create policy accounts_read on public.accounts
  for select to authenticated using (public.is_member());
create policy accounts_admin_insert on public.accounts
  for insert to authenticated with check (public.is_admin());
create policy accounts_admin_update on public.accounts
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy accounts_admin_delete on public.accounts
  for delete to authenticated using (public.is_admin());

create policy categories_read on public.categories
  for select to authenticated using (public.is_member());
create policy categories_admin_insert on public.categories
  for insert to authenticated with check (public.is_admin());
create policy categories_admin_update on public.categories
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy categories_admin_delete on public.categories
  for delete to authenticated using (public.is_admin());

create policy transactions_read on public.transactions
  for select to authenticated using (public.is_member());
create policy transactions_insert on public.transactions
  for insert to authenticated with check (public.is_member() and created_by = auth.uid());
create policy transactions_update on public.transactions
  for update to authenticated
  using (public.is_member() and (public.is_admin() or created_by = auth.uid()))
  with check (public.is_member() and (public.is_admin() or created_by = auth.uid()));
create policy transactions_delete on public.transactions
  for delete to authenticated
  using (public.is_member() and (public.is_admin() or created_by = auth.uid()));

-- Nothing is readable without signing in.
revoke all on public.profiles, public.accounts, public.categories, public.transactions from anon;

-- ---------------------------------------------------------------------
-- Views (run with the caller's permissions, so the policies above apply)
-- ---------------------------------------------------------------------
create view public.account_balances with (security_invoker = true) as
select
  a.id, a.name, a.type, a.opening_balance, a.note, a.is_active, a.created_at,
  a.opening_balance
    + coalesce((select sum(case when t.type = 'Income' then t.amount else -t.amount end)
                from public.transactions t where t.account_id = a.id), 0)
    + coalesce((select sum(t.amount)
                from public.transactions t where t.type = 'Transfer' and t.to_account_id = a.id), 0)
    as balance
from public.accounts a;

create view public.transaction_details with (security_invoker = true) as
select
  t.id, t.type, t.amount, t.date,
  t.account_id, a.name as account_name,
  t.to_account_id, ta.name as to_account_name,
  t.category_id, c.name_en as category_name_en, c.name_bn as category_name_bn,
  c.icon as category_icon, c.color as category_color,
  t.member_id, m.name as member_name,
  t.note,
  t.created_by, cb.name as created_by_name,
  t.created_at
from public.transactions t
join public.accounts a on a.id = t.account_id
left join public.accounts ta on ta.id = t.to_account_id
left join public.categories c on c.id = t.category_id
left join public.profiles m on m.id = t.member_id
left join public.profiles cb on cb.id = t.created_by;

revoke all on public.account_balances, public.transaction_details from anon;

-- ---------------------------------------------------------------------
-- Functions called by the app (security invoker: policies apply)
-- ---------------------------------------------------------------------
create function public.filtered_transactions(
  p_from date, p_to date,
  p_type text default null, p_account bigint default null,
  p_member uuid default null, p_search text default null)
returns setof public.transaction_details
language sql stable set search_path = public as $$
  select * from public.transaction_details d
  where d.date between p_from and p_to
    and (p_type is null or d.type = p_type)
    and (p_account is null or d.account_id = p_account or d.to_account_id = p_account)
    and (p_member is null or d.member_id = p_member)
    and (p_search is null or p_search = ''
         or d.note ilike '%' || p_search || '%'
         or d.category_name_en ilike '%' || p_search || '%'
         or d.category_name_bn ilike '%' || p_search || '%');
$$;

create function public.list_transactions(
  p_from date, p_to date,
  p_type text default null, p_account bigint default null,
  p_member uuid default null, p_search text default null,
  p_limit int default 50, p_offset int default 0)
returns setof public.transaction_details
language sql stable set search_path = public as $$
  select * from public.filtered_transactions(p_from, p_to, p_type, p_account, p_member, p_search)
  order by date desc, id desc
  limit least(greatest(p_limit, 1), 200) offset greatest(p_offset, 0);
$$;

create function public.transaction_summary(
  p_from date, p_to date,
  p_type text default null, p_account bigint default null,
  p_member uuid default null, p_search text default null)
returns table (total bigint, income numeric, expense numeric)
language sql stable set search_path = public as $$
  select count(*),
         coalesce(sum(amount) filter (where type = 'Income'), 0),
         coalesce(sum(amount) filter (where type = 'Expense'), 0)
  from public.filtered_transactions(p_from, p_to, p_type, p_account, p_member, p_search);
$$;

create function public.dashboard(p_year int, p_month int)
returns jsonb
language plpgsql stable set search_path = public as $$
declare
  s  date := make_date(p_year, p_month, 1);
  e  date := (make_date(p_year, p_month, 1) + interval '1 month')::date;
  ts date := (make_date(p_year, p_month, 1) - interval '5 months')::date;
  v_income  numeric;
  v_expense numeric;
begin
  select coalesce(sum(amount) filter (where type = 'Income'), 0),
         coalesce(sum(amount) filter (where type = 'Expense'), 0)
    into v_income, v_expense
  from public.transactions where date >= s and date < e;

  return jsonb_build_object(
    'year', p_year,
    'month', p_month,
    'income', v_income,
    'expense', v_expense,
    'net', v_income - v_expense,
    'totalBalance', coalesce((select sum(balance) from public.account_balances where is_active), 0),
    'accounts', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', id, 'name', name, 'type', type, 'openingBalance', opening_balance,
               'balance', balance, 'note', note, 'isActive', is_active) order by name)
      from public.account_balances where is_active), '[]'::jsonb),
    'expenseByCategory', coalesce((
      select jsonb_agg(x order by (x ->> 'amount')::numeric desc)
      from (select jsonb_build_object('categoryId', c.id, 'nameEn', c.name_en, 'nameBn', c.name_bn,
                                      'icon', c.icon, 'color', c.color, 'amount', sum(t.amount)) as x
            from public.transactions t join public.categories c on c.id = t.category_id
            where t.type = 'Expense' and t.date >= s and t.date < e
            group by c.id) q), '[]'::jsonb),
    'expenseByMember', coalesce((
      select jsonb_agg(x order by (x ->> 'amount')::numeric desc)
      from (select jsonb_build_object('memberId', t.member_id, 'name', coalesce(p.name, ''),
                                      'amount', sum(t.amount)) as x
            from public.transactions t left join public.profiles p on p.id = t.member_id
            where t.type = 'Expense' and t.date >= s and t.date < e
            group by t.member_id, p.name) q), '[]'::jsonb),
    'trend', (
      select jsonb_agg(jsonb_build_object(
               'year', extract(year from m)::int, 'month', extract(month from m)::int,
               'income', coalesce((select sum(amount) from public.transactions
                                   where type = 'Income' and date >= m and date < m + interval '1 month'), 0),
               'expense', coalesce((select sum(amount) from public.transactions
                                    where type = 'Expense' and date >= m and date < m + interval '1 month'), 0))
             order by m)
      from generate_series(ts, s, interval '1 month') as g(m)),
    'recent', coalesce((
      select jsonb_agg(to_jsonb(d) order by d.date desc, d.id desc)
      from (select * from public.transaction_details order by date desc, id desc limit 6) d), '[]'::jsonb)
  );
end;
$$;

revoke execute on function public.filtered_transactions, public.list_transactions,
  public.transaction_summary, public.dashboard from anon;

